test('discard removes a verified dirty worktree but preserves ignored data', async t => {
  const f = await fixture(t)
  await writeFile(join(f.isolated, 'task.txt'), 'discard me\n')
  const discarded = await f.act('discard', await f.latest())
  assert.equal(discarded.cleanup?.status, 'done')
  assert.equal(await exists(f.isolated), false)
  assert.equal(await git(f.local, 'rev-parse', 'HEAD'), f.base)
  const second = await fixture(t)
  await mkdir(join(second.isolated, 'cache'))
  await writeFile(join(second.isolated, 'cache', 'private'), 'preserve me')
  const retained = await second.act('discard', await second.latest())
  assert.equal(retained.phase, 'discarded')
  assert.equal(retained.cleanup?.status, 'retained')
  assert.equal(retained.cleanup?.canForce, true)
  const proof = await second.store.inspectRetainedRemoval(retained, second.local)
  await assert.rejects(second.store.removeRetained(retained.id, second.isolated, proof), /当前 Pi 会话或进程/)
  await writeFile(join(second.isolated, 'cache/private'), 'written after confirmation')
  await assert.rejects(second.store.removeRetained(retained.id, second.local, proof), /确认期间发生变化/)
  assert.equal(await content(second.isolated, 'cache/private'), 'written after confirmation')
  assert.equal((await second.latest()).journal, undefined)
  const currentProof = await second.store.inspectRetainedRemoval(await second.latest(), second.local)
  await second.store.holdWorktree(retained.id)
  try {
    await assert.rejects(second.store.removeRetained(retained.id, second.local, currentProof), /另一个 Pi 会话正在使用/)
    assert.equal(await exists(second.isolated), true)
    assert.equal((await second.latest()).journal, undefined)
  } finally { await second.store.releaseWorktree(retained.id) }
  await git(second.local, 'worktree', 'lock', second.isolated)
  await assert.rejects(second.store.removeRetained(retained.id, second.local, currentProof), /已锁定/)
  await git(second.local, 'worktree', 'unlock', second.isolated)
  const gitDir = retained.isolated!.gitDir
  await mkdir(join(gitDir, 'modules'))
  await assert.rejects(second.store.inspectRetainedRemoval(retained, second.local), /Git 子模块/)
  await rm(join(gitDir, 'modules'), { recursive: true })
  await writeFile(join(gitDir, 'index.lock'), '')
  await assert.rejects(second.store.inspectRetainedRemoval(retained, second.local), /Git 索引仍被锁定/)
  await rm(join(gitDir, 'index.lock'))
  const nested = join(second.isolated, 'cache', 'nested')
  await mkdir(nested)
  await git(nested, 'init', '--bare')
  await assert.rejects(second.store.inspectRetainedRemoval(await second.latest(), second.local), /嵌套的裸 Git 仓库/)
  await rm(nested, { recursive: true })
  await second.store.removeRetained(retained.id, second.local, await second.store.inspectRetainedRemoval(await second.latest(), second.local))
  assert.equal((await second.latest()).cleanup?.status, 'done')
  assert.equal(await exists(second.isolated), false)
  assert.equal(await git(second.local, 'rev-parse', 'HEAD'), second.base)
})
