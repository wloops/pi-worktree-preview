const git = async (cwd: string, ...args: string[]) => (await runGit(cwd, args)).stdout.toString()
const content = async (cwd: string, file: string) => readFile(join(cwd, file), 'utf8')
const exists = (path: string) => stat(path).then(() => true, () => false)

async function fixture(t: TestContext, engine?: typeof createSessionCheckoutApplyEngine, empty = false) {
  const dir = await realpath(await mkdtemp(join(tmpdir(), 'pi-wtp-test-')))
  t.after(() => rm(dir, { recursive: true, force: true }))
  const local = join(dir, 'Local with spaces')
  await mkdir(local)
  await git(local, 'init', '-b', 'main')
  await git(local, 'config', 'user.name', 'Test')
  await git(local, 'config', 'user.email', 'test@localhost')
  if (!empty) {
    for (const file of ['task.txt', 'staged.txt', 'unstaged.txt']) await writeFile(join(local, file), `${file} base\n`)
    await writeFile(join(local, '.gitignore'), 'cache/\n')
    await git(local, 'add', '.')
  }
  await git(local, 'commit', '--allow-empty', '-m', 'base')
  // Git versions that materialize an empty index on commit need this to
  // reproduce repositories where no index file was ever written.
  if (empty) await rm(join(local, '.git/index'), { force: true })
  const base = await git(local, 'rev-parse', 'HEAD')
  const store = new TaskStore(join(dir, 'state'), engine)
  const task = await store.create(await checkout(local), { cwd: local, id: 'local', file: join(dir, 'local.jsonl') },
    async cwd => ({ cwd, id: 'isolated', file: join(dir, 'isolated.jsonl') }))
  const isolated = task.isolatedPath
  const latest = async () => (await store.read()).tasks[0]
  const act = async (action: Parameters<TaskStore['act']>[1], current: Task, revision?: Parameters<TaskStore['act']>[2]['revision']) => store.act(task.id, action, {
    phase: current.phase, reviewId: current.review?.id, previewId: current.receipt?.previewId, revision,
    discardFingerprint: action === 'discard' ? await store.discardFingerprint(current) : undefined,
  })
  const ready = () => store.markReady(task.id, task.isolatedSession!, 'Task only')
  return { dir, local, isolated, store, base, latest, act, ready, task }
}

test('journaled preview, rollback, re-preview and task-only commit preserve Local layers', async t => {
  const { local, isolated, store, base, latest, act, ready } = await fixture(t)
  await writeFile(join(local, 'staged.txt'), 'staged content\n')
  await git(local, 'add', 'staged.txt')
  await writeFile(join(local, 'staged.txt'), 'working over staged\n')
  await writeFile(join(local, 'unstaged.txt'), 'unstaged content\n')
  await writeFile(join(local, 'user.txt'), 'untracked content\n')
  await writeFile(join(isolated, 'task.txt'), 'task change\n')
  await writeFile(join(isolated, 'bin.dat'), Buffer.from([0, 1, 0xff, 0x80]))
  await git(isolated, 'add', 'bin.dat')
  await git(isolated, 'commit', '-m', 'isolated commit')
  const status = await git(local, 'status', '--porcelain=v1')
  const staged = await git(local, 'diff', '--cached')
  const unstaged = await git(local, 'diff')
  await ready()
  assert.equal(await git(local, 'status', '--porcelain=v1'), status)
  const preview = await act('preview', await latest())
  assert.equal(preview.phase, 'previewed')
  assert.equal(await git(local, 'rev-parse', 'HEAD'), base)
  assert.equal(await git(local, 'diff', '--cached'), staged)
  assert.equal(await content(local, 'task.txt'), 'task change\n')
  assert.deepEqual(await readFile(join(local, 'bin.dat')), Buffer.from([0, 1, 0xff, 0x80]))
  assert.match(await git(local, 'for-each-ref', 'refs/pi-worktree-preview'), /snapshot-0/)
  const rolled = await act('rollback', await latest())
  assert.equal(rolled.phase, 'ready')
  assert.equal(rolled.review?.id, preview.review?.id)
  assert.equal(await git(local, 'status', '--porcelain=v1'), status)
  assert.equal(await git(local, 'diff'), unstaged)
  assert.equal(await git(local, 'diff', '--cached'), staged)
  assert.equal(await exists(join(local, 'bin.dat')), false)
  await act('preview', await latest())
  const delivered = await act('finalize', await latest())
  assert.equal(delivered.phase, 'delivered')
  assert.equal(delivered.cleanup?.status, 'done')
  assert.equal(await exists(isolated), false)
  assert.equal(await git(local, 'show', '-s', '--format=%s'), 'Task only\n')
  assert.equal(await git(local, 'show', '--format=', '--name-only'), 'bin.dat\ntask.txt\n')
  assert.equal(await git(local, 'diff', '--cached'), staged)
  assert.equal(await git(local, 'diff'), unstaged)
  assert.equal(await content(local, 'user.txt'), 'untracked content\n')
  assert.equal(await exists(store.lockPath), false)
})

test('separate Local sessions develop in parallel but share one Local preview', async t => {
  const f = await fixture(t)
  const local = await checkout(f.local)
  const secondSession = { cwd: f.local, id: 'second-local', file: join(f.dir, 'second-local.jsonl') }
  const createSession = async (cwd: string, task: Task) => ({ cwd, id: task.id, file: join(f.dir, `${task.id}.jsonl`) })
  await writeFile(join(f.isolated, 'task.txt'), 'first task\n')
  await f.ready()
  await f.act('preview', await f.latest())
  // Creation and editing are independent of the current Local preview.
  const second = await f.store.create(local, secondSession, createSession)
  assert.notEqual(second.isolatedPath, f.isolated)
  assert.equal(await content(second.isolatedPath, 'task.txt'), 'task.txt base\n')
  await assert.rejects(f.store.create(local, secondSession, createSession), /此 Local 会话已有未完成/)
  await writeFile(join(second.isolatedPath, 'second.txt'), 'second task\n')
  const reviewed = await f.store.markReady(second.id, second.isolatedSession!, 'Second task only')
  const secondPreview = () => f.store.act(second.id, 'preview', { phase: 'ready', reviewId: reviewed.id })
  const state = await f.store.read()
  await assert.rejects(secondPreview(), /正在预览另一个任务/)
  assert.deepEqual(await f.store.read(), state)
  assert.equal(await exists(join(f.local, 'second.txt')), false)
  assert.equal(await content(f.local, 'task.txt'), 'first task\n')

  // Both rollback and finalize release the slot for the next session.
  await f.act('rollback', await f.latest())
  const preview = await secondPreview()
  await assert.rejects(f.act('preview', await f.latest()), /正在预览另一个任务/)
  await f.act('discard', await f.latest()) // Does not alter the second preview.
  assert.equal(await content(f.local, 'second.txt'), 'second task\n')
  assert.equal(await content(f.local, 'task.txt'), 'task.txt base\n')
  await f.store.act(second.id, 'finalize', { phase: 'previewed', reviewId: reviewed.id, previewId: preview.receipt?.previewId })
  assert.equal(await git(f.local, 'show', '--format=', '--name-only'), 'second.txt\n')

  const third = await f.store.create(local, f.task.localSession, createSession)
  assert.equal(await content(third.isolatedPath, 'second.txt'), 'second task\n')
  await writeFile(join(third.isolatedPath, 'task.txt'), 'third task\n')
  const thirdReview = await f.store.markReady(third.id, third.isolatedSession!, 'Third task only')
  await f.store.act(third.id, 'preview', { phase: 'ready', reviewId: thirdReview.id })
  assert.equal(await content(f.local, 'task.txt'), 'third task\n')
})

test('follow-up requires closed history for the same Local and takes the current branch HEAD', async t => {
  const f = await fixture(t)
  const fork = async (cwd: string, task: Task, prior?: Task) => {
    assert.equal(prior?.id, f.task.id)
    assert.equal(await exists(cwd), false, 'validate the source session before creating a worktree')
    return { cwd, id: task.id, file: join(f.dir, `${task.id}.jsonl`) }
  }
  await assert.rejects(f.store.create(await checkout(f.local), f.task.localSession, fork, f.task.id), /已有未完成/)
  await writeFile(join(f.isolated, 'discarded.txt'), 'not carried forward\n')
  const closed = await f.act('discard', await f.latest())
  assert.equal(closed.cleanup?.status, 'done')
  assert.equal(await exists(f.isolated), false)
  const other = join(f.dir, 'other-local')
  await git(f.local, 'worktree', 'add', '-b', 'other-local', other)
  await assert.rejects(f.store.create(await checkout(other), f.task.localSession, fork, closed.id), /不属于同一个 Local/)
  await assert.rejects(f.store.create(await checkout(f.local), f.task.localSession, fork, 'no-such-task'), /原任务不可续接/)
  await assert.rejects(f.store.create(await checkout(f.local), f.task.localSession, async () => { throw new Error('missing session') }, closed.id), /missing session/)
  assert.deepEqual((await f.store.read()).tasks, [closed])

  await git(f.local, 'switch', '-c', 'later-branch')
  await writeFile(join(f.local, 'latest.txt'), 'new base\n')
  await git(f.local, 'add', 'latest.txt')
  await git(f.local, 'commit', '-m', 'new tip')
  await writeFile(join(f.local, 'task.txt'), 'uncommitted Local\n')
  const next = await f.store.create(await checkout(f.local), f.task.localSession, fork, closed.id)
  assert.equal(next.followUpOf, closed.id)
  assert.equal(next.phase, 'working')
  assert.equal(next.localHeadRef, 'refs/heads/later-branch')
  assert.equal(next.baseOid, (await git(f.local, 'rev-parse', 'HEAD')).trim())
  assert.equal(await content(next.isolatedPath, 'latest.txt'), 'new base\n')
  assert.equal(await content(next.isolatedPath, 'task.txt'), 'task.txt base\n')
  assert.equal(await exists(join(next.isolatedPath, 'discarded.txt')), false)
  assert.deepEqual(await f.latest(), closed)
})

test('continuing edits invalidates only the matching review, with or without a prior preview', async t => {
  const f = await fixture(t)
  const session = f.task.isolatedSession!
  await writeFile(join(f.isolated, 'task.txt'), 'first revision\n')
  const old = await f.ready()
  const ready = await f.latest()
  await assert.rejects(f.store.continueEditing(f.task.id, f.task.localSession, old.id), /不能继续修改/)
  await assert.rejects(f.store.continueEditing(f.task.id, session, 'stale'), /不能继续修改/)
  const signal = AbortSignal.abort(new Error('cancelled revision'))
  await assert.rejects(f.store.continueEditing(f.task.id, session, old.id, signal), /cancelled revision/)
  assert.equal((await f.latest()).review?.id, old.id)
  await f.store.continueEditing(f.task.id, session, old.id)
  assert.equal((await f.latest()).phase, 'working')
  assert.equal((await f.latest()).review, undefined)
  assert.equal(await content(f.isolated, 'task.txt'), 'first revision\n')
  assert.equal(await content(f.local, 'task.txt'), 'task.txt base\n')
  await assert.rejects(f.act('preview', ready), /任务状态已变化/)

  await writeFile(join(f.isolated, 'task.txt'), 'second revision\n')
  const current = await f.ready()
  assert.notEqual(current.id, old.id)
  const preview = await f.act('preview', await f.latest())
  await assert.rejects(f.store.continueEditing(f.task.id, session, current.id), /不能继续修改/)
  await assert.rejects(f.act('rollback', preview, { session: f.task.localSession }), /不能继续修改/)
  await assert.rejects(f.act('rollback', preview, { session, signal }), /cancelled revision/)
  assert.equal(await content(f.local, 'task.txt'), 'second revision\n')
  assert.equal((await f.latest()).journal, undefined)
  await writeFile(join(f.local, 'task.txt'), 'user edit after preview\n')
  await assert.rejects(f.act('rollback', preview, { session }), /预览路径自预览后已变化.*task\.txt/)
  assert.equal((await f.latest()).phase, 'previewed')
  assert.equal((await f.latest()).review?.id, current.id)
  assert.equal((await f.latest()).receipt?.previewId, preview.receipt?.previewId)
  assert.equal(await content(f.local, 'task.txt'), 'user edit after preview\n')
  await writeFile(join(f.local, 'task.txt'), 'second revision\n')
  const working = await f.act('rollback', await f.latest(), { session })
  assert.equal(working.phase, 'working')
  assert.equal(working.review, undefined)
  assert.equal(working.receipt, undefined)
  assert.equal(working.journal, undefined)
  assert.equal(await content(f.isolated, 'task.txt'), 'second revision\n')
  assert.equal(await content(f.local, 'task.txt'), 'task.txt base\n')
  assert.equal(await git(f.local, 'rev-parse', 'HEAD'), f.base)
})

